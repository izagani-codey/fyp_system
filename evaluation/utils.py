def notify(user, message, email_subject=None, email_body=None):
    """
    Create an in-app notification and send an email.
    During development, emails are printed to the console (EMAIL_BACKEND = console).
    """
    Notification.objects.create(user=user, message=message)

    subject = email_subject or "FYP Evaluation System — Notification"
    body = email_body or message
    try:
        send_mail(
            subject=subject,
            message=body,
            from_email=settings.DEFAULT_FROM_EMAIL,
            recipient_list=[user.email],
            fail_silently=True,
        )
    except Exception:
        pass


def ranked_project_results(course=None):
    """Return approved projects ranked by accepted evaluation average score."""
    projects = (
        Project.objects.filter(registration_status="approved")
        .select_related("course", "leader")
        .prefetch_related("assignments__judge", "assignments__eval_submission")
    )
    if course:
        projects = projects.filter(course=course)

    rows = []
    for project in projects:
        assignments = list(project.assignments.all())
        submissions = []
        for assignment in assignments:
            try:
                submissions.append(assignment.eval_submission)
            except EvaluationSubmission.DoesNotExist:
                pass

        accepted_submissions = [s for s in submissions if s.status == "accepted"]
        final_score = None
        if accepted_submissions:
            total = sum((s.total_score for s in accepted_submissions), Decimal("0"))
            final_score = total / Decimal(len(accepted_submissions))

        rows.append(
            {
                "project": project,
                "assignment_count": len(assignments),
                "submitted_count": len(submissions),
                "accepted_count": len(accepted_submissions),
                "pending_count": sum(
                    1 for s in submissions if s.status == "pending_review"
                ),
                "rejected_count": sum(1 for s in submissions if s.status == "rejected"),
                "eval_submissions": submissions,
                "final_score": final_score,
                "rank": None,
            }
        )

    rankable = sorted(
        [row for row in rows if row["final_score"] is not None],
        key=lambda row: row["final_score"],
        reverse=True,
    )
    for index, row in enumerate(rankable, start=1):
        row["rank"] = index

    return sorted(
        rows,
        key=lambda row: (
            row["rank"] is None,
            row["rank"] or 999999,
            row["project"].title,
        ),
    )


def generate_top3_content(course=None):
    """Build public winner-announcement text without exposing private marks."""
    ranked = [
        row
        for row in ranked_project_results(course=course)
        if row["rank"] and row["rank"] <= 3
    ]
    scope = course.name if course else "Overall"
    if not ranked:
        return None, None

    title = f"{scope} Top 3 FYP Winners"
    lines = [
        f"{scope} Top 3 FYP winners have been generated by PIC based on accepted judge evaluations only.",
        "",
    ]
    for row in ranked:
        project = row["project"]
        course_name = (
            project.course.name
            if project.course
            else project.programme or "Unassigned Course"
        )
        lines.append(
            f"Rank {row['rank']}: {project.title} — {course_name} — Section {project.section}"
        )
    lines.extend(
        [
            "",
            "Individual marks remain confidential and are not published to students.",
            "Congratulations to all winners.",
        ]
    )
    return title, "\n".join(lines)


def export_results_csv(course=None):
    """
    Generate a CSV with project, course, assignment, evaluation, score, rank,
    and submission status information.
    """
    response = HttpResponse(content_type="text/csv")
    filename = f"fyp_results_{timezone.now().strftime('%Y%m%d_%H%M')}.csv"
    response["Content-Disposition"] = f'attachment; filename="{filename}"'

    writer = csv.writer(response)
    writer.writerow(
        [
            "Project Title",
            "Course",
            "Section",
            "Supervisor",
            "Project Leader",
            "Assigned Judge(s)",
            "Submission Status",
            "Evaluation Status",
            "Final Average Score",
            "Rank",
            "Reviewed/Accepted Status",
        ]
    )

    for row in ranked_project_results(course=course):
        project = row["project"]
        judge_names = (
            ", ".join(a.judge.full_name for a in project.assignments.all())
            or "Not assigned"
        )
        if row["assignment_count"] == 0:
            evaluation_status = "Not assigned"
        elif row["accepted_count"] == row["assignment_count"]:
            evaluation_status = "All accepted"
        else:
            evaluation_status = (
                f"Accepted {row['accepted_count']}/{row['assignment_count']}; "
                f"Pending {row['pending_count']}; Rejected {row['rejected_count']}; "
                f"Not submitted {row['assignment_count'] - row['submitted_count']}"
            )
        try:
            submission_status = project.submission.get_status_display()
        except Exception:
            submission_status = "Not Submitted"

        # Calculate reviewed/accepted status for evaluation submissions
        if row["accepted_count"] > 0:
            reviewed_status = f"{row['accepted_count']} accepted"
        elif row["pending_count"] > 0:
            reviewed_status = f"{row['pending_count']} pending review"
        elif row["rejected_count"] > 0:
            reviewed_status = f"{row['rejected_count']} rejected"
        else:
            reviewed_status = "No evaluations"

        writer.writerow(
            [
                project.title,
                project.course.name if project.course else project.programme or "Unassigned",
                project.section,
                project.supervisor_name,
                project.leader.full_name if project.leader else "Unassigned",
                judge_names,
                submission_status,
                evaluation_status,
                f"{row['final_score']:.2f}" if row["final_score"] is not None else "No score",
                row["rank"] if row["rank"] else "Unranked",
                reviewed_status,
            ]
        )

    return response
